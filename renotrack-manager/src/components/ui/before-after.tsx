export function BeforeAfter({ before, after, label }: { before: string; after: string; label: string }) {
  const [pos, setPos] = useState(50);
  return (
    <div className="relative aspect-[4/3] w-full select-none overflow-hidden rounded-xl border border-outline-variant bg-surface-container has-[input:focus-visible]:outline-2 has-[input:focus-visible]:outline-offset-2 has-[input:focus-visible]:outline-primary">
      <img src={after} alt={`${label} — planned render`} className="absolute inset-0 h-full w-full object-cover" />
      <div className={cn("absolute inset-0 overflow-hidden", clipClass[pos])}>
        <img src={before} alt={`${label} — current site photo`} className="absolute inset-0 h-full w-full object-cover" />
      </div>
      <div className={cn("pointer-events-none absolute inset-y-0", leftClass[pos])}>
        <div className="h-full w-0.5 -translate-x-1/2 bg-surface-container-lowest" />
        <div className="absolute top-1/2 grid size-11 -translate-x-1/2 -translate-y-1/2 place-items-center rounded-full border-2 border-surface-container-lowest bg-primary" />
      </div>
      <span className="absolute top-3 left-3 rounded-full bg-surface-container-lowest px-3 py-1 text-label-md text-on-surface">Now</span>
      <span className="absolute top-3 right-3 rounded-full bg-primary px-3 py-1 text-label-md text-on-primary">Planned</span>
      <input
        type="range"
        min={0}
        max={100}
        step={1}
        value={pos}
        onChange={(e) => setPos(Math.round(Number(e.target.value)))}
        aria-label={`Compare current and planned ${label}`}
        className="peer absolute inset-0 h-full w-full cursor-ew-resize opacity-0"
      />
    </div>
  );
}
